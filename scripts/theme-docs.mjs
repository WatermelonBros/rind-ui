// Generates docs/theme/tokens.md from packages/theme/tokens.manifest.json.
// Run: node scripts/theme-docs.mjs   ·   --check fails when the page is out of date.
import { existsSync, readFileSync, writeFileSync } from "node:fs"

const root = new URL("../", import.meta.url)
const manifest = JSON.parse(
  readFileSync(new URL("packages/theme/tokens.manifest.json", root), "utf8"),
)
const out = new URL("docs/theme/tokens.md", root)

const category = (t) => /^--rind-([a-z]+)/.exec(t)?.[1] ?? "other"

/** Markdown of the token reference. */
export function renderTokens(m) {
  const groups = new Map()
  for (const t of m.tier2) groups.set(category(t), [...(groups.get(category(t)) ?? []), t])
  const comps = Object.entries(m.components ?? {})
  return [
    "<!-- Generated by scripts/theme-docs.mjs from packages/theme/tokens.manifest.json. Do not edit. -->",
    "",
    "# Token reference",
    "",
    "Every tier 2 (semantic) token and every component's tier 3 token. Tier 1 are the twelve `--rind-brand-*` inputs; see [white-label.md](white-label.md).",
    "",
    "## Tier 2: semantic tokens",
    "",
    "| Category | Tokens |",
    "|---|---|",
    ...[...groups].map(([c, ts]) => `| ${c} | ${ts.map((t) => `\`${t}\``).join(", ")} |`),
    "",
    "## Runtime tokens",
    "",
    "Written by rind-ui at run time (positioning, scroll lock, animation); readable, not themeable.",
    "",
    ...m.runtime.map((t) => `- \`${t}\``),
    "",
    "## Tier 3: component tokens",
    "",
    ...(comps.length === 0
      ? ["_No component stylesheet declares tokens yet._", ""]
      : comps.flatMap(([scope, tokens]) => [
          `### ${scope}`,
          "",
          "```json",
          JSON.stringify(tokens, null, 2),
          "```",
          "",
        ])),
  ].join("\n")
}

if (import.meta.main) {
  const text = renderTokens(manifest)
  if (process.argv.includes("--check")) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
      console.error("docs/theme/tokens.md is out of date (run node scripts/theme-docs.mjs)")
      process.exit(1)
    }
  } else writeFileSync(out, text)
}
