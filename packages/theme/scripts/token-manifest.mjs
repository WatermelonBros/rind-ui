// Scans src/*.css for component-token reads var(--rind-<scope>-<name>, <fallback>) and writes
// tokens.manifest.json (tier-2 list + component tokens with fallback and family) and
// src/builder/components.generated.ts (the `components` override type of defineTheme).
// Run: node packages/theme/scripts/token-manifest.mjs (pnpm --filter @rind-ui/theme generate)
import { readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs"
import { allComponents, familyOf, noFamily } from "../src/families.ts"

const root = new URL("../", import.meta.url)
const src = new URL("src/", root)
// Tier-2 categories (--rind-hit-area is tier 2 too), brand inputs and icons; never components.
const tier2 = new Set(
  "color space size radius text font leading tracking shadow duration ease focus border brand icon hit".split(
    " ",
  ),
)
// Written at runtime by core (positioning, scroll lock, animation): documented, not themeable.
const runtimeRe =
  /^(x|y|position|available-.+|anchor-.+|transform-origin|arrow-.+|collision-padding|scrollbar-width|pop-from|[a-z-]+-content-(?:height|width))$/
// Not scanned: tokens.css reads only tiers 1-2, the rest is generated.
const skip = new Set(["index.css", "tokens.css", "icons.css"])

const strip = (css) => css.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "))

/** Every var(--rind-…) read: `{ name (without --rind-), fallback | null, line }`. */
export function reads(css) {
  const text = strip(css)
  const out = []
  for (const m of text.matchAll(/var\(\s*--rind-([a-z0-9-]+)\s*/g)) {
    let i = m.index + m[0].length
    let fallback = null
    if (text[i] === ",") {
      let depth = 1
      const start = ++i
      for (; i < text.length && depth > 0; i++) {
        if (text[i] === "(") depth++
        else if (text[i] === ")") depth--
      }
      fallback = text.slice(start, i - 1).trim()
    }
    out.push({ name: m[1], fallback, line: text.slice(0, m.index).split("\n").length })
  }
  return out
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const known = [...allComponents, ...noFamily]

function split(name, file) {
  // Longest known component scope that prefixes the name, else the file's own scope, else the
  // first segment (a component whose row is not in families.ts yet).
  const scopes = [...known, file.replace(/\.css$/, "")]
  const scope = scopes
    .filter((s) => name.startsWith(`${s}-`))
    .sort((a, b) => b.length - a.length)[0]
  if (scope) return { scope, token: name.slice(scope.length + 1) }
  const [first, ...rest] = name.split("-")
  return { scope: first, token: rest.join("-") }
}

const tier2Names = [
  ...new Set(
    [
      ...strip(readFileSync(new URL("tokens.css", src), "utf8")).matchAll(
        /(--rind-[a-z0-9-]+)\s*:/g,
      ),
    ]
      .map((m) => m[1])
      .filter((n) => tier2.has(n.split("-")[3]) && !n.startsWith("--rind-brand-")),
  ),
].sort()

const scopes = {}
const runtime = new Set()
for (const file of readdirSync(src).filter((f) => f.endsWith(".css") && !skip.has(f))) {
  for (const r of reads(readFileSync(new URL(file, src), "utf8"))) {
    // A known component scope wins over a category prefix (scope text-field vs category text),
    // unless the name is itself a semantic token.
    const full = `--rind-${r.name}`
    const isComponent = known.some((s) => r.name.startsWith(`${s}-`)) && !tier2Names.includes(full)
    if (!isComponent && tier2.has(r.name.split("-")[0])) continue
    if (runtimeRe.test(r.name)) {
      runtime.add(`--rind-${r.name}`)
      continue
    }
    const { scope, token } = split(r.name, file)
    const entry = scopes[scope] ?? { family: familyOf(scope) ?? null, tokens: {} }
    scopes[scope] = entry
    if (!(token in entry.tokens)) entry.tokens[token] = { fallback: r.fallback, file }
  }
}
const sortKeys = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)))
const manifest = {
  tier2: tier2Names,
  runtime: [...runtime].sort(),
  components: sortKeys(
    Object.fromEntries(
      Object.entries(scopes).map(([s, e]) => [s, { ...e, tokens: sortKeys(e.tokens) }]),
    ),
  ),
}

const names = Object.entries(manifest.components)
const ts = `// Generated by scripts/token-manifest.mjs from the component stylesheets. Do not edit.
// Component scope → its tier-3 token names (camel case), for \`defineTheme({ components })\`.
export type ComponentTokens = ${
  names.length === 0
    ? "Record<never, never>"
    : `{\n${names
        .map(
          ([s, e]) =>
            `  readonly ${JSON.stringify(s)}: ${Object.keys(e.tokens)
              .map((t) => JSON.stringify(camel(t)))
              .join(" | ")}`,
        )
        .join("\n")}\n}`
}
`

const repo = new URL("../../../", import.meta.url)
// Build outputs, not committed (.gitignore): the theme's `generate` task writes them before
// build and typecheck; the site writes them before reading the manifest. Written through a
// rename so a concurrent run (turbo's typecheck beside the site's) never reads half a file.
function put(path, text) {
  const url = new URL(path, repo)
  const tmp = new URL(`${path}.${process.pid}.tmp`, repo)
  writeFileSync(tmp, text)
  renameSync(tmp, url)
}
put("packages/theme/tokens.manifest.json", `${JSON.stringify(manifest, null, 2)}\n`)
put("packages/theme/src/builder/components.generated.ts", ts)
