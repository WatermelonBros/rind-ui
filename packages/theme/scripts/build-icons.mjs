// Generates src/icons.css (--rind-icon-<name> tokens) from @phosphor-icons/core, decision 0010.
// Usage: node scripts/build-icons.mjs [--weight regular|bold] [--stdout]
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

const NAMES = [
  "check",
  "minus",
  "x",
  "caret-down",
  "caret-up",
  "caret-left",
  "caret-right",
  "magnifying-glass",
  "eye",
  "eye-slash",
  "plus",
  "calendar",
  "clock",
  "warning",
  "info",
  "check-circle",
  "x-circle",
  "dots-three",
  "arrow-left",
  "arrow-right",
  "copy",
]

const args = process.argv.slice(2)
const wi = args.indexOf("--weight")
const weight = wi < 0 ? "regular" : args[wi + 1]
if (weight !== "regular" && weight !== "bold") {
  console.error(`--weight must be regular or bold, got ${weight}`)
  process.exit(1)
}

// The package has an exports map without package.json, so resolve its folder directly.
const root = fileURLToPath(new URL("../node_modules/@phosphor-icons/core", import.meta.url))
const suffix = weight === "regular" ? "" : `-${weight}`
// Minimal encoding for a double-quoted url(): only characters CSS or URL parsing would misread.
const encode = (svg) =>
  svg
    .trim()
    .replace(/"/g, "'")
    .replace(/%/g, "%25")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .replace(/#/g, "%23")
    .replace(/\r?\n/g, "%0A")
const tokens = NAMES.map((name) => {
  const svg = readFileSync(join(root, "assets", weight, `${name}${suffix}.svg`), "utf8")
  return `    --rind-icon-${name}: url("data:image/svg+xml,${encode(svg)}");`
})
// Declared on :root only: icons are not derived per scope, so a global override on :root
// reaches every [data-rind-theme] scope, and a tenant still overrides on its own scope.
const css = `/* Generated by packages/theme/scripts/build-icons.mjs from @phosphor-icons/core (${weight}). Do not edit. */
@layer rind {
  :where(:root) {
${tokens.join("\n")}
  }
}
`
if (args.includes("--stdout")) process.stdout.write(css)
else writeFileSync(new URL("../src/icons.css", import.meta.url), css)
